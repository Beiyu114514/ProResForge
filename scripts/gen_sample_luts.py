#!/usr/bin/env python3
"""生成 ProResForge 示例 LUT(.cube 3D, SIZE 17)。

用法: python3 scripts/gen_sample_luts.py
输出: sample-luts/*.cube

说明: 这些是"创意风格" LUT,用于验证 LUT 嵌入转码管线是否工作;
      相机/监视器厂家发布的 33 点 LUT(如 S-Log3->Rec.709)可直接放入本目录使用,
      管线解析逻辑(.cube/.3dl)与点数无关。
"""
import os
import math

SIZE = 17


def clamp01(v: float) -> float:
    return 0.0 if v < 0.0 else (1.0 if v > 1.0 else v)


def scurve(v: float, k: float = 1.15) -> float:
    """温和 S 曲线, 增加对比但不死黑/惨白。"""
    return clamp01(0.5 + (v - 0.5) * k + 0.06 * math.sin(2.0 * math.pi * v - math.pi))


def identity(r, g, b):
    return r, g, b


def teal_orange(r, g, b):
    l = 0.2126 * r + 0.7152 * g + 0.0722 * b
    # 阴影偏青, 高光偏橙
    shadow = clamp01(l) * (1.0 - clamp01(l))
    rr = scurve(r) + 0.10 * shadow * (1.0 - l)
    gg = scurve(g) + 0.02 * shadow * (1.0 - l)
    bb = scurve(b) + 0.14 * clamp01(l) * 0.35
    gg -= 0.05 * clamp01(1.0 - l) * 0.30  # 阴影去绿偏青
    return clamp01(rr), clamp01(gg), clamp01(bb)


def golden_hour(r, g, b):
    rr = scurve(r, 1.08) * 1.06 + 0.03
    gg = scurve(g, 1.04) * 1.00
    bb = scurve(b, 0.98) * 0.88 - 0.02
    return clamp01(rr), clamp01(gg), clamp01(bb)


def write_cube(path, title, fn):
    lines = [
        f"TITLE \"{title}\"",
        "# Generated by ProResForge scripts/gen_sample_luts.py",
        "LUT_3D_SIZE %d" % SIZE,
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
        "",
    ]
    # .cube 顺序: R 变化最快, then G, then B
    for b in range(SIZE):
        for g in range(SIZE):
            for r in range(SIZE):
                rv, gv, bv = r / (SIZE - 1), g / (SIZE - 1), b / (SIZE - 1)
                rr, gg, bb = fn(rv, gv, bv)
                lines.append("%.6f %.6f %.6f" % (rr, gg, bb))
    # 显式 utf-8 + \n:不依赖运行环境的 locale(Windows 上 cp936 会写出 GBK 字节,
    # Android 侧按 UTF-8 读会乱码;PYTHONUTF8 / XDG 未设定的 CI 上同理)。
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


def main():
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sample-luts")
    os.makedirs(out_dir, exist_ok=True)
    write_cube(os.path.join(out_dir, "identity_passthrough.cube"), "Identity (管线校验用)", identity)
    write_cube(os.path.join(out_dir, "teal_orange_17.cube"), "Teal & Orange (示例创意)", teal_orange)
    write_cube(os.path.join(out_dir, "golden_hour_17.cube"), "Golden Hour (示例暖调)", golden_hour)


if __name__ == "__main__":
    main()
